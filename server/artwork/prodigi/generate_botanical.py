#!/usr/bin/env python3
"""Original parametric botanical artwork. Python standard library only.
Run: python3 generate_botanical.py [output.svg]
SVG is vector-only, with a 12 x 16 inch page; no raster images or external assets.
"""
import math
import sys
from pathlib import Path

W,H=900,1200
NAVY='#102635'
CREAM='#eee3c7'
GOLD='#c9a76b'
SAGE='#95a68a'
DARK_SAGE='#617d73'
GOLDEN_ANGLE=math.pi*(3-math.sqrt(5))
parts=[]
def put(s): parts.append(s)
def circle(x,y,r,fill='none',stroke=GOLD,sw=.7,opacity=1):
 put(f'<circle cx="{x:.3f}" cy="{y:.3f}" r="{r:.3f}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" opacity="{opacity}"/>')
def path(d,stroke=CREAM,sw=1,fill='none',opacity=1):
 put(f'<path d="{d}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" opacity="{opacity}" stroke-linecap="round" stroke-linejoin="round"/>')
def line(x1,y1,x2,y2,stroke=GOLD,sw=.7,opacity=1):
 path(f'M {x1:.3f} {y1:.3f} L {x2:.3f} {y2:.3f}',stroke,sw,opacity=opacity)

def leaf(x,y,length,angle,width=.25,colour=SAGE):
 # A pointed leaf from two cubic Bezier curves; arcing secondary veins.
 put(f'<g transform="translate({x:.3f} {y:.3f}) rotate({angle:.3f})">')
 a=length;b=length*width
 path(f'M 0 0 C {a*.25} {-b} {a*.72} {-b*.88} {a} 0 C {a*.65} {b*.75} {a*.22} {b*.72} 0 0',CREAM,.75,colour)
 path(f'M 0 0 Q {a*.54} {-b*.12} {a} 0',CREAM,.8)
 for j in range(1,8):
  t=j/9
  for sign in [-1,1]:
   # End each vein inside its actual cubic boundary, rather than a sine approximation.
   c1,c2=(.25,.72) if sign<0 else (.22,.65)
   v1,v2=(1,.88) if sign<0 else (.72,.75)
   xx=a*(3*(1-t)**2*t*c1+3*(1-t)*t*t*c2+t**3)
   yy=sign*b*(3*(1-t)**2*t*v1+3*(1-t)*t*t*v2)*.94
   start=max(a*.025,xx-a*.12)
   path(f'M {start:.3f} {-b*.035:.3f} Q {(start+xx)/2:.3f} {yy*.6:.3f} {xx:.3f} {yy:.3f}',CREAM,.5,opacity=.74)
 put('</g>')

def petal(angle,r0,r1,width,fill):
 put(f'<g transform="rotate({angle:.4f})">')
 path(f'M 0 {-r0:.3f} C {-width:.3f} {-r0-(r1-r0)*.28:.3f} {-width*.54:.3f} {-r1+5:.3f} 0 {-r1:.3f} C {width*.54:.3f} {-r1+5:.3f} {width:.3f} {-r0-(r1-r0)*.28:.3f} 0 {-r0:.3f}',CREAM,.85,fill)
 path(f'M 0 {-r0-3:.3f} Q {-width*.12:.3f} {-(r0+r1)/2:.3f} 0 {-r1+9:.3f}',GOLD,.6,opacity=.8)
 put('</g>')

def flower(cx,cy,radius,petals,seeds):
 put(f'<g transform="translate({cx} {cy})">')
 # An outer compass circle makes the generated geometry visible.
 circle(0,0,radius*1.075,sw=.7,opacity=.48)
 for k in range(12):
  a=k*math.tau/12
  line(math.cos(a)*radius*1.105,math.sin(a)*radius*1.105,math.cos(a)*radius*1.145,math.sin(a)*radius*1.145,sw=.7,opacity=.65)
 for i in range(petals):
  petal(i*360/petals,radius*.46,radius*(.96+.04*math.cos(i*math.tau*5/petals)),radius*.08,CREAM if i%3 else GOLD)
 circle(0,0,radius*.51,NAVY,GOLD,1.3)
 # Vogel's phyllotaxis: r = c sqrt(n), theta = n * golden angle.
 for n in range(seeds):
  theta=n*GOLDEN_ANGLE
  rr=radius*.474*math.sqrt((n+.5)/seeds)
  x=rr*math.cos(theta);y=rr*math.sin(theta)
  seedsize=radius*.018*(.72+.28*math.sqrt((n+1)/seeds))
  put(f'<ellipse cx="{x:.3f}" cy="{y:.3f}" rx="{seedsize:.3f}" ry="{seedsize*.62:.3f}" transform="rotate({math.degrees(theta)+31:.3f} {x:.3f} {y:.3f})" fill="{GOLD if n%8<3 else CREAM}"/>')
 circle(0,0,radius*.505,sw=.8)
 put('</g>')

def fern(base_x,base_y,scale,side):
 # A planar arch with paired, geometrically shortening pinnae.
 put(f'<g transform="translate({base_x} {base_y}) scale({side*scale} {scale})">')
 path('M 0 0 C 88 -77 103 -184 65 -260',SAGE,2.3)
 for j in range(13):
  t=(j+1)/15
  # Evaluate the stem cubic at t.
  x=3*(1-t)**2*t*88+3*(1-t)*t*t*103+t**3*65
  y=3*(1-t)**2*t*(-77)+3*(1-t)*t*t*(-184)+t**3*(-260)
  length=64*(1-t)**.55
  leaf(x,y,length,-155+t*45,.12,DARK_SAGE)
  leaf(x,y,length*.84,-24-t*37,.12,DARK_SAGE)
 put('</g>')

def make_svg():
 parts.clear()
 put('<svg xmlns="http://www.w3.org/2000/svg" width="12in" height="16in" viewBox="0 0 900 1200">')
 put('<title>Moonlit Botanicals — Phyllotaxis I</title><desc>Original botanical geometry constructed with Bezier leaves, Vogel golden-angle seed patterns and paired fern fronds. Vector artwork generated by code.</desc>')
 put(f'<rect width="900" height="1200" fill="{NAVY}"/>')
 # Quiet etched border, substantial clear margin around all botanical elements.
 put(f'<rect x="36" y="36" width="828" height="1128" rx="166" fill="none" stroke="{GOLD}" stroke-width=".8" opacity=".7"/>')
 put(f'<rect x="45" y="45" width="810" height="1110" rx="158" fill="none" stroke="{GOLD}" stroke-width=".5" opacity=".27"/>')
 # Sparse geometric starfield; positions follow an irrational sequence.
 for i in range(66):
  x=100+700*((i*.61803398875)%1)
  y=100+960*((i*.41421356237)%1)
  if ((x-450)/185)**2+((y-392)/185)**2<1.2:continue
  if ((x-244)/112)**2+((y-741)/112)**2<1.2:continue
  if ((x-670)/118)**2+((y-660)/118)**2<1.2:continue
  circle(x,y,.85 if i%5 else 1.4,GOLD,'none',opacity=.42)
 # Lunar emblem drawn with circular arcs, without raster masks.
 circle(450,133,46,sw=.65,opacity=.55)
 path('M 461 101 A 34 34 0 1 0 471 158 A 31 31 0 0 1 461 101',GOLD,.65,GOLD)
 for x,y,size in [(450,66,5),(389,134,4),(511,134,4),(450,199,4)]:
  line(x-size,y,x+size,y,CREAM,.8);line(x,y-size,x,y+size,CREAM,.8)
 # Branch architecture.
 path('M 450 1095 C 439 929 467 733 450 470',CREAM,3.4)
 path('M 448 1055 C 392 977 316 895 246 835',CREAM,2.7)
 path('M 453 991 C 554 902 631 821 669 758',CREAM,2.7)
 # Golden companion traces follow the stems, giving an engraved finish.
 path('M 456 1090 C 445 920 473 740 456 477',GOLD,.65,opacity=.7)
 path('M 446 1042 C 386 961 313 891 251 840',GOLD,.65)
 path('M 459 986 C 560 894 634 816 674 762',GOLD,.65)
 # Rhythmic leaves of differing scale, alternating along stems.
 for args in [
  (449,1010,152,-158,.25,SAGE),(453,953,151,-29,.24,DARK_SAGE),
  (450,878,147,-147,.26,SAGE),(457,801,141,-35,.23,SAGE),
  (454,717,111,-145,.24,DARK_SAGE),(451,642,98,-36,.23,SAGE),
  (356,942,102,-169,.23,DARK_SAGE),(317,902,102,-105,.23,SAGE),
  (553,897,103,-7,.23,SAGE),(603,840,94,-87,.22,DARK_SAGE),
  (245,837,73,-172,.2,SAGE),(669,761,74,-7,.2,SAGE),
 ]:leaf(*args)
 fern(370,1063,.95,-1)
 fern(529,1070,.93,1)
 flower(450,392,150,34,377)
 flower(244,741,94,21,233)
 flower(670,660,102,34,233)
 # A symmetric seed-shaped root ornament anchors the composition.
 put('<g transform="translate(450 1095)">')
 for i in range(8):
  a=i*math.tau/8
  circle(18*math.cos(a),18*math.sin(a),18,sw=.65,opacity=.75)
 circle(0,0,4,CREAM,'none')
 put('</g>')
 put('</svg>')
 return '\n'.join(parts)+'\n'

if __name__=='__main__':
 output=Path(sys.argv[1]) if len(sys.argv)>1 else Path(__file__).with_name('moonlit-botanicals-phyllotaxis.svg')
 output.write_text(make_svg())
 print(output)
